// Utility to generate YAML config and JSON schemas from form data

// Sanitize table name to be valid YAML key and file name
const sanitizeTableName = (name) => {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9_]/g, '_')  // Replace non-alphanumeric with underscore
    .replace(/^[0-9]/, '_$&')      // Prefix with underscore if starts with number
    .replace(/_+/g, '_')           // Replace multiple underscores with single
    .replace(/^_+|_+$/g, '');      // Remove leading/trailing underscores
};

export const generateYAMLConfig = (formData) => {
  const yaml = `# ${formData.projectName} - ETL Configuration
  # Generated by CRYVEX Pipeline Creator
  
  project:
    name: "${formData.projectName}"
    domain: "${formData.domain}"
    version: "${formData.version}"
    description: "${formData.description}"
  
  # ==================== GLOBAL SETTINGS ====================
  global:
    # Database configuration (shared)
    database:
      type: "${formData.database.type}"
      host: "${formData.database.host}"
      port: ${formData.database.port}
      database: "${formData.database.database}"
      username: "${formData.database.username}"
      password: "${formData.database.password}"
    
    # Blockchain configuration (shared)
    blockchain:
      enabled: ${formData.blockchain.enabled}
      network: "${formData.blockchain.network}"
      rpc_url: "${formData.blockchain.rpcUrl}"
      contract_address: "${formData.blockchain.contractAddress}"
      private_key: "${formData.blockchain.privateKey}"
      abi_file: "/opt/airflow/include/etl_modules/abi.json"
    
    # Pipeline settings (shared)
    pipeline:
      batch_size: 1000
      log_level: "INFO"
    
    # Encryption configuration
    ${generateEncryptionYAML(formData.tables)}
  
  # ==================== EXECUTION SETTINGS ====================
  execution:
    mode: "${formData.executionMode}"
    stop_on_error: ${formData.stopOnError}
    max_parallel_tasks: 4
  
  # ==================== TABLE DEFINITIONS ====================
  tables:
  ${generateTablesYAML(formData.tables)}
  
  # ==================== DERIVED TABLES ====================
  ${formData.derivedTables && formData.derivedTables.length > 0 ? `derived_tables:\n${generateDerivedTablesYAML(formData.derivedTables)}` : '# No derived tables defined'}
  `;
  return yaml;
};

const generateEncryptionYAML = (tables) => {
  // Collect all encryption configurations from all tables
  const allEncryptions = [];
  tables.forEach(table => {
    if (table.encryption && table.encryption.length > 0) {
      table.encryption.forEach(enc => {
        if (enc.column && enc.method) {
          allEncryptions.push(enc);
        }
      });
    }
  });

  if (allEncryptions.length === 0) {
    return `encryption:
      enabled: false`;
  }

  return `encryption:
      enabled: true
      master_key: "\${CRYVEX_MASTER_KEY}"  # Reads from environment variable
      
      columns:
${allEncryptions.map(enc => `        - column: "${enc.column}"
          method: "${enc.method}"`).join('\n        \n')}`;
};

const generateTablesYAML = (tables) => {
  if (!tables || tables.length === 0) {
    return '  # No tables defined';
  }
  return tables.map(table => {
    const tableName = sanitizeTableName(table.name || 'unnamed_table');
    const originalTableName = table.name || 'unnamed_table';
    const depends = table.dependsOn && table.dependsOn.length > 0
      ? `[${table.dependsOn.map(d => `"${sanitizeTableName(d)}"`).join(', ')}]`
      : '[]';

    return `
    # ============================================================
    # Table: ${originalTableName.toUpperCase()}
    # ============================================================
    ${tableName}:
      priority: ${table.priority}
      depends_on: ${depends}

      # Source configuration
      source:
        file:
          path: "/opt/airflow/datasets/data/test/${table.sourceFileName || 'data.csv'}"
          type: "csv"
          encoding: "utf-8"
          delimiter: ","
          has_header: true

      # Column mapping
      mapping:
        auto_map: true
        unmapped_columns: "ignore"

      # Target configuration
      target:
        table_name: "${tableName}"
        if_exists: "${table.ifExists}"
        create_if_not_exists: true

      # Schema definition
      schema:
        file: "/opt/airflow/pipeline_configs/schemas/${tableName}_schema.json"
      ${generateTransformationsYAML(table.transformations)}${generateValidationsYAML(table.validations)}`;
  }).join('\n');
};

const generateDerivedTablesYAML = (derivedTables) => {
  if (!derivedTables || derivedTables.length === 0) {
    return '  # No derived tables defined';
  }
  return derivedTables.map(table => {
    // Use customName if name is 'custom', otherwise use name
    const rawTableName = table.name === 'custom'
      ? (table.customName || 'unnamed_derived_table')
      : (table.name || 'unnamed_derived_table');
    const tableName = sanitizeTableName(rawTableName);
    const depends = table.dependsOn && table.dependsOn.length > 0
      ? `[${table.dependsOn.map(d => `"${sanitizeTableName(d)}"`).join(', ')}]`
      : '[]';
    const targetTableName = sanitizeTableName(table.targetTableName || tableName);

    // Format SQL query with proper indentation
    const sqlLines = (table.sqlQuery || '').split('\n');
    const indentedSQL = sqlLines.map((line, index) => {
      if (index === 0) return line;
      return `        ${line}`;
    }).join('\n');

    return `
    # ============================================================
    # Derived Table: ${rawTableName.toUpperCase()}
    # ============================================================
    ${tableName}:
      priority: ${table.priority}
      depends_on: ${depends}

      # Query configuration
      query:
        type: "${table.queryType}"
        sql: |
          ${indentedSQL}

      # Target configuration
      target:
        table_name: "${targetTableName}"
        if_exists: "${table.ifExists}"
        create_if_not_exists: true`;
  }).join('\n');
};

const generateTransformationsYAML = (transformations) => {
  if (!transformations || transformations.length === 0) return '';

  const lines = transformations.map(t => {
    let line = `          - column: "${t.column}"\n            action: "${t.action}"`;
    if (t.action === 'round' && t.decimals) {
      line += `\n            decimals: ${t.decimals}`;
    }
    return line;
  }).join('\n');

  return `\n      # Transformations\n      transformations:\n        inline:\n${lines}\n`;
};

const generateValidationsYAML = (validations) => {
  if (!validations || validations.length === 0) return '';

  const lines = validations.map(v => {
    let line = `          - column: "${v.column}"\n            rule: "${v.rule}"`;

    const ruleOption = [
      { value: 'min_value', needsValue: true },
      { value: 'max_value', needsValue: true },
      { value: 'min_length', needsValue: true },
      { value: 'max_length', needsValue: true },
      { value: 'in_list', needsValue: true, isList: true }
    ].find(r => r.value === v.rule);

    if (ruleOption?.needsValue && v.value) {
      if (ruleOption.isList) {
        const values = v.value.split(',').map(val => val.trim());
        line += `\n            values: [${values.map(val => `"${val}"`).join(', ')}]`;
      } else {
        line += `\n            value: ${v.value}`;
      }
    }
    return line;
  }).join('\n');

  return `\n      # Validations\n      validations:\n        inline:\n${lines}\n`;
};

export const generateJSONSchema = (table, domain = "generic") => {
  const tableName = sanitizeTableName(table.name || 'unnamed_table');

  return {
    domain: domain,
    table_name: tableName,
    description: `Schema for ${tableName} table`,
    columns: (table.schema?.columns || []).map(col => {
      const column = {
        name: col.name,
        type: col.type,
        nullable: col.nullable !== undefined ? col.nullable : true
      };

      // Add max_length for string types
      if (col.type === 'string' && col.maxLength) {
        column.max_length = col.maxLength;
      }

      // Add primary_key and unique for primary keys
      if (col.primaryKey) {
        column.primary_key = true;
        column.unique = true;
      }

      // Filter out undefined/null values
      Object.keys(column).forEach(key => {
        if (column[key] === undefined || column[key] === null) {
          delete column[key];
        }
      });

      return column;
    }).filter(col => col.name && col.name.trim() !== '') // Only include columns with names
  };
};

export const downloadFile = (content, filename, contentType = 'text/plain') => {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};

export const generateFiles = (formData) => {
  // Generate YAML config
  const yamlContent = generateYAMLConfig(formData);
  const configFileName = `${formData.projectName.toLowerCase().replace(/\s+/g, '_')}_config.yaml`;

  // Generate JSON schemas for each table
  const schemas = (formData.tables || []).map(table => {
    return generateJSONSchema(table, formData.domain || "generic");
  });
  // Always return valid JSON, even if empty array
  const schemasJson = JSON.stringify(schemas, null, 2);

  return {
    yamlContent,
    configFileName,
    schemas,
    schemasJson
  };
};

export const generateAndDownloadFiles = (formData) => {
  // Generate files
  const { yamlContent, configFileName, schemas } = generateFiles(formData);

  // Download YAML config
  downloadFile(yamlContent, configFileName, 'text/yaml');

  // Download JSON schemas for each table (only if table has columns)
  const downloadedSchemas = [];
  schemas.forEach((schema, index) => {
    // Only download if schema has columns
    if (schema.columns && schema.columns.length > 0) {
      const schemaContent = JSON.stringify(schema, null, 2);
      const tableName = formData.tables[index]?.name || `table_${index + 1}`;
      const schemaFileName = `${tableName}_schema.json`;
      downloadFile(schemaContent, schemaFileName, 'application/json');
      downloadedSchemas.push(schemaFileName);
    }
  });

  return {
    configFile: configFileName,
    schemaFiles: downloadedSchemas
  };
};